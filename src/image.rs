use gtk4::gio;
use log::{debug, error};
use std::fs;
use std::path::PathBuf;

use crate::insta360;

pub const SUPPORTED_FILE_TYPES: &[(&str, &str)] = &[
    ("jpg", "image/jpeg"),
    ("jpeg", "image/jpeg"),
    ("png", "image/png"),
    ("webp", "image/webp"),
    // Insta360 photos: a JPEG holding both fisheye circles, with the camera's
    // own trailer behind it.
    ("insp", "image/jpeg"),
];

pub struct ImageData {
    pub filename: String,
    pub data: Vec<u8>,
    pub mime_type: String,
    /// Parameters for the viewer's dual-fisheye projection, as JSON. `None` for
    /// an ordinary equirectangular image.
    pub dual_fisheye: Option<String>,
}

pub fn from_file(path: &PathBuf) -> ImageData {
    if !path.exists() {
        error!("File {:?} does not exist", path);
        return from_demo();
    }

    let name = path
        .file_name()
        .and_then(|n| n.to_str())
        .unwrap_or("")
        .to_string();

    let mime_type = match detect_mime_type(path) {
        Some(m) => m.to_string(),
        None => {
            error!("Could not detect mime type for {:?}", path);
            return from_demo();
        }
    };

    match fs::read(path) {
        Ok(data) => {
            let (data, dual_fisheye) = split_insta360(data);
            ImageData {
                filename: name,
                data,
                mime_type,
                dual_fisheye,
            }
        }
        Err(e) => {
            error!("Could not read file {:?}: {}", path, e);
            from_demo()
        }
    }
}

pub fn from_demo() -> ImageData {
    gio::resources_lookup_data(
        "/io/github/dynobo/sphereview/assets/demo.webp",
        gio::ResourceLookupFlags::NONE,
    )
    .map(|bytes| ImageData {
        filename: "demo.webp".to_string(),
        data: bytes.to_vec(),
        mime_type: "image/webp".to_string(),
        dual_fisheye: None,
    })
    .expect("demo.webp should always be available in GIO resources")
}

pub fn detect_mime_type<P: AsRef<std::path::Path>>(path: P) -> Option<&'static str> {
    path.as_ref()
        .extension()
        .and_then(std::ffi::OsStr::to_str)
        .and_then(|ext| {
            SUPPORTED_FILE_TYPES
                .iter()
                .find(|(e, _)| e.eq_ignore_ascii_case(ext))
                .map(|(_, mt)| *mt)
        })
}

/// Takes an Insta360 photo apart into the image and the projection parameters.
///
/// A `.insp` is a JPEG with the camera's trailer behind it. The trailer is not
/// part of the image and the viewer has no use for those bytes, so what goes to
/// the webview stops at the end of the JPEG.
///
/// Detection is by content, not by name: an Insta360 photo that has been renamed
/// still works, and a `.insp` without the trailer falls back to being shown as
/// the plain JPEG it is.
fn split_insta360(data: Vec<u8>) -> (Vec<u8>, Option<String>) {
    let Some(trailer) = insta360::read(&data) else {
        return (data, None);
    };

    debug!(
        "Insta360 photo: trailer v{}, model {:?}, calibration {}, {} of {} bytes are image",
        trailer.version,
        trailer.model.as_deref().unwrap_or("unknown"),
        if trailer.calibration.is_some() {
            "found"
        } else {
            "missing"
        },
        trailer.body_len,
        data.len(),
    );

    let params = trailer.params_json();
    if params.is_none() {
        log::warn!("Insta360 photo without a lens calibration, shown without projection");
    }

    let mut data = data;
    data.truncate(trailer.body_len);
    (data, params)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn fixture(name: &str) -> PathBuf {
        PathBuf::from(env!("CARGO_MANIFEST_DIR"))
            .join("tests/fixtures")
            .join(name)
    }

    #[test]
    fn insp_is_reported_as_a_jpeg() {
        assert_eq!(detect_mime_type("IMG_0001.insp"), Some("image/jpeg"));
        assert_eq!(detect_mime_type("IMG_0001.INSP"), Some("image/jpeg"));
    }

    #[test]
    fn plain_jpeg_is_left_alone() {
        let jpeg = vec![0xFF, 0xD8, 0xFF, 0xDB, 0x00, 0xFF, 0xD9];
        let (data, params) = split_insta360(jpeg.clone());
        assert_eq!(data, jpeg);
        assert!(params.is_none());
    }

    /// The committed fixture is synthetic: generated by `tools/make_synthetic_insp.py`,
    /// so no camera's copyright is involved. It proves the wiring - extension,
    /// trailer, parameter JSON, JPEG/trailer split - not a camera's conventions.
    #[test]
    fn synthetic_insp_yields_projection_parameters() {
        let path = fixture("synthetic.insp");
        let image = from_file(&path);

        assert_eq!(image.mime_type, "image/jpeg");
        let params = image
            .dual_fisheye
            .expect("the fixture carries a calibration");

        for expected in ["\"lens_count\":2", "\"fov_deg\":194", "\"lens\":["] {
            assert!(params.contains(expected), "missing {expected} in {params}");
        }

        // The trailer must not reach the browser.
        assert!(
            image.data.ends_with(&[0xFF, 0xD9]),
            "image should end at the JPEG EOI"
        );
        assert!(image.data.len() < fs::read(&path).expect("fixture").len());
    }
}
